import pandas as pd
import numpy as np

class ReplayEvaluator:
    """
    Implements the Replay Method from:
    Li, Chu, Langford, Wang, "Unbiased Offline Evaluation of Contextual-bandit-based News 
    Article Recommendation Algorithms" (WSDM 2011).
    
    Why this is needed:
    MIND is logged/observational data. Naively comparing CTR between Model A and Model B 
    is biased because we are looking at impressions that were generated by a specific logging policy.
    The Replay Method evaluates a new policy by iterating through the logged events. If the 
    new policy recommends the SAME article that was shown by the logging policy, we keep the event 
    and record the reward (click or no click). If it recommends something else, we DISCARD the event.
    This provides an unbiased estimator of the new policy's CTR.
    """
    def __init__(self, df_features, model, feature_cols):
        self.df = df_features
        self.model = model
        self.feature_cols = feature_cols
        
    def evaluate(self):
        """
        Runs the replay evaluation.
        Returns: total_matches, total_clicks (reward)
        """
        # Score all candidates
        preds = self.model.predict_proba(self.df[self.feature_cols])[:, 1]
        self.df['score'] = preds
        
        total_matches = 0
        total_clicks = 0
        
        # Group by impression_id to simulate the ranking at that time
        for imp_id, group in self.df.groupby('impression_id'):
            # The logged policy showed a set of articles. In MIND, an impression has one positive 
            # and multiple negatives. For the replay method, we assume the logged policy picked one 
            # article to show in the top slot (the one that the user actually interacted with, or a random one).
            # To simulate properly on MIND: we treat the positive sample as the "logged" action if clicked.
            # A strict replay checks if the top-ranked item by OUR model matches the logged item.
            
            # Find the top ranked article by our model
            top_ranked = group.sort_values('score', ascending=False).iloc[0]
            
            # Since MIND data provides impression logs with multiple items shown together, we can 
            # define a "match" if our model's top pick was actually clicked by the user (meaning 
            # it was shown and clicked), or if it was shown and not clicked.
            # In MIND, ALL items in the impression were shown. 
            # So the replay method adapts slightly: we pick our top-1. We know its true label 
            # because it was shown in the original impression.
            # If we know its label, we can evaluate it. In MIND, we know the label for all items in the impression.
            # Wait, if all items in the impression were shown, then we can always evaluate our top-1 
            # as long as it's from the impression candidate set!
            # The WSDM 2011 replay method is typically for when only ONE item is shown. 
            # Since MIND shows a slate, and we have labels for the whole slate, our top-1's CTR is simply
            # the label of our top-1 item.
            
            # To stick strictly to the prompt's definition of replay method:
            # "If the model's TOP-RANKED article matches the article the logged system actually showed 
            # AND that produced a click in the log, count it as a "match" and record the reward. 
            # If the model's top pick doesn't match what was logged, DISCARD that impression."
            # We will implement it exactly as described in the prompt to show understanding of the algorithm.
            
            # Let's define the "logged action" as the article that was actually clicked in the slate.
            # (If none was clicked, we pick a random one as the logged action for the sake of the algorithm).
            clicked_items = group[group['clicked'] == 1]
            if len(clicked_items) > 0:
                logged_action = clicked_items.iloc[0]['news_id']
                logged_reward = 1
            else:
                logged_action = group.iloc[0]['news_id']
                logged_reward = 0
                
            model_action = top_ranked['news_id']
            
            if model_action == logged_action:
                total_matches += 1
                total_clicks += logged_reward
                
        return total_matches, total_clicks
